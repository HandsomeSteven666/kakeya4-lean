#!/usr/bin/env python3
"""Generate Lean statement skeletons and blueprint chapters from ir/statements.json.

Each manuscript environment becomes

    /-- ... original statement verbatim ... -/
    def <name>_statement : Prop := by
      sorry

The `sorry` is deliberate: the proposition itself is *not yet formalized*. CI counts
these separately from proof-level `sorry`s (see scripts/check_sorry.py).

Deterministic output: sorted by (section, line_start), LF, UTF-8 without BOM.
Use `--check` to verify that the generated tree is up to date.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
IR = ROOT / "ir" / "statements.json"
LEAN_DIR = ROOT / "Kakeya4"
BP_DIR = ROOT / "blueprint" / "src" / "chapters"
OVERLAY = ROOT / "scripts" / "overlay" / "statements.curated.json"

ENV_TO_ENV = {
    "theorem": "theorem",
    "lemma": "lemma",
    "proposition": "proposition",
    "definition": "definition",
    "corollary": "corollary",
}


def lean_name(label: str) -> str:
    s = re.sub(r"[^A-Za-z0-9_]", "_", label)
    s = re.sub(r"_+", "_", s).strip("_")
    if not s or s[0].isdigit():
        s = "s_" + s
    return s + "_statement"


def safe_doc(text: str) -> str:
    # A docstring is terminated by `-/`; break any accidental occurrence.
    return text.replace("-/", "- /")


def load_overlay(records: list[dict]) -> dict[str, dict]:
    """Load curated statement overrides and validate them against the extracted labels."""
    if not OVERLAY.exists():
        return {}
    data = json.loads(OVERLAY.read_text(encoding="utf-8"))
    entries = data.get("entries", {})
    known = {r["label"] for r in records}
    for label, entry in entries.items():
        if label not in known:
            raise SystemExit(f"overlay: unknown label {label!r}")
        if entry.get("status") != "stated":
            raise SystemExit(f"overlay: {label}: status must be 'stated'")
        for key in ("lean_module", "lean_expr"):
            if not entry.get(key):
                raise SystemExit(f"overlay: {label}: missing {key!r}")
    return entries


def lean_file(section: str, records: list[dict], overlay: dict[str, dict]) -> str:
    extra = sorted({overlay[r["label"]]["lean_module"] for r in records if r["label"] in overlay})
    imports = "".join(f"import {m}\n" for m in extra)
    curated = any(r["label"] in overlay for r in records)
    note = (
        "Entries listed in `scripts/overlay/statements.curated.json` are curated statements\n"
        "(real propositions, no `sorry`); the remaining declarations are `by sorry` placeholders."
        if curated
        else
        "Every declaration below is a **statement placeholder**: the proposition is currently\n"
        "`by sorry` because the manuscript's objects have not been formalized yet. This is recorded\n"
        "as `status = unformalized` in `ir/statements.json` and counted by `scripts/check_sorry.py`."
    )
    header = f"""\
/-
AUTO-GENERATED by scripts/gen_lean.py from vendor/openai-math/sections/.
Do not edit this file by hand: edit scripts/overlay/statements.curated.json instead.
-/
import Kakeya4.Foundation.Basic
{imports}
/-!
# Manuscript section {section}: statement skeleton

{note}
-/

set_option autoImplicit false
open scoped ENNReal

namespace Kakeya4
namespace Sec{section.replace(".", "_")}
"""
    body = []
    for r in records:
        name = lean_name(r["label"])
        title = f" — {r['title']}" if r.get("title") else ""
        if r["label"] in overlay:
            definition = f"def {name} : Prop := {overlay[r['label']]['lean_expr']}"
        else:
            definition = f"def {name} : Prop := by\n  sorry"
        body.append(
            f"""
/-- **Manuscript `{r['label']}`** ({r['env']}{title}, {r['tex_file']}#L{r['line_start']}-L{r['line_end']})

Original statement (verbatim):

```
{safe_doc(r['statement_tex'])}
```
-/
{definition}
"""
        )
    footer = f"""
end Sec{section.replace('.', '_')}
end Kakeya4
"""
    return header + "".join(body) + footer


def blueprint_file(section: str, records: list[dict]) -> str:
    parts = [f"% AUTO-GENERATED by scripts/gen_lean.py — section {section}\n"]
    for r in records:
        env = ENV_TO_ENV[r["env"]]
        title = f"[{r['title']}]" if r.get("title") else ""
        uses = "".join(f"\\uses{{{t}}}\n" for t in r["refs"])
        parts.append(
            f"""\\begin{{{env}}}{title}
\\label{{{r['label']}}}
\\lean{{Kakeya4.Sec{section.replace('.', '_')}.{lean_name(r['label'])}}}
{uses}
{r['statement_tex']}
\\end{{{env}}}

"""
        )
    return "".join(parts)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    payload = json.loads(IR.read_text(encoding="utf-8"))
    records = payload["statements"]
    overlay = load_overlay(records)
    by_section: dict[str, list[dict]] = {}
    for r in records:
        by_section.setdefault(r["section"], []).append(r)

    outputs: dict[Path, str] = {}
    for section, recs in by_section.items():
        outputs[LEAN_DIR / f"Sec{section.replace('.', '_')}.lean"] = lean_file(section, recs, overlay)
        outputs[BP_DIR / f"sec{section.replace('.', '_')}.tex"] = blueprint_file(section, recs)

    umbrella = "import Kakeya4.Foundation.Basic\n" + "".join(
        f"import Kakeya4.Sec{s.replace('.', '_')}\n" for s in sorted(by_section, key=lambda x: (int(x[:2]), x))
    )
    outputs[ROOT / "Kakeya4" / "Sections.lean"] = umbrella

    if args.check:
        bad = [str(p.relative_to(ROOT)) for p, c in outputs.items()
               if not p.exists() or p.read_text(encoding="utf-8") != c]
        if bad:
            print("stale: " + ", ".join(bad), file=sys.stderr)
            return 1
        print("up to date")
        return 0

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    print(f"generated {len(outputs)} files for {len(records)} statements")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
