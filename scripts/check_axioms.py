LINE_RE = re.compile(r"'([^']+)' depends on axioms: \[([^\]]*)\]")
NO_AXIOM_RE = re.compile(r"'([^']+)' does not depend on any axioms")


def main() -> int:
    env = dict(os.environ)
    env.setdefault("LEAN_NUM_THREADS", "1")
    proc = subprocess.run(
        ["lake", "env", "lean", str(AUDIT.relative_to(ROOT))],
        cwd=ROOT, capture_output=True, text=True, env=env,
    )
    out = proc.stdout + proc.stderr
    found = {}
    for m in LINE_RE.finditer(out):
        found[m.group(1)] = {x.strip() for x in m.group(2).split(",") if x.strip()}
    for m in NO_AXIOM_RE.finditer(out):
        found.setdefault(m.group(1), set())

    if proc.returncode != 0:
        print(out, file=sys.stderr)
        print(f"audit failed (exit {proc.returncode})", file=sys.stderr)
        return 1

    problems = []
    for name in EXPECTED:
        if name not in found:
            problems.append(f"missing audit line for {name}")
            continue
        extra = found[name] - STANDARD - ALLOWED_EXTRA
        if extra:
            problems.append(f"{name} uses non-standard axioms: {sorted(extra)}")
    if problems:
        for p in problems:
            print(p, file=sys.stderr)
        return 1

    clean = [n for n in EXPECTED if "sorryAx" not in found[n]]
    print(f"axiom audit ok: {len(found)} declarations, {len(clean)} sorry-free")
    for n in clean:
        print(f"  clean: {n}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
